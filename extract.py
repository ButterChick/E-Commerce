# Fields that must be non-null for a row to be valid
_CRITICAL_FIELDS = ("order_item_id", "order_id", "order_date", "customer_id", "product_id")


def transform(
    orders: DataFrame,
    customers: DataFrame,
    products: DataFrame,
    etl_run_id: str,
) -> DataFrame:
    """
    Join orders with customers and products, clean, deduplicate, compute
    revenue/margin fields, and enforce a final column order.

    Cleaning steps (applied before any computation):
      1. Drop rows where any critical field (order_item_id, order_id,
         order_date, customer_id, product_id) is NULL.
      2. Drop rows with quantity <= 0 or unit_price <= 0.
      3. Deduplicate on order_item_id, keeping the first occurrence after
         ordering by order_id descending (latest wins on re-delivery).

    Args:
        orders:      Output of extract_orders().
        customers:   Output of extract_customers().
        products:    Output of extract_products().
        etl_run_id:  UUID string generated by run_pipeline(); shared with
                     load.py so fact rows and audit log carry the same ID.

    Returns:
        Cleaned, enriched Spark DataFrame ready for write_parquet().
    """
    from pyspark.sql.window import Window

    # --- 1. Drop nulls on critical fields ---
    null_filter = F.col(_CRITICAL_FIELDS[0]).isNotNull()
    for field in _CRITICAL_FIELDS[1:]:
        null_filter = null_filter & F.col(field).isNotNull()

    # --- 2. Drop non-positive quantity / price ---
    clean = (
        orders
        .filter(null_filter)
        .filter(F.col("quantity") > 0)
        .filter(F.col("unit_price") > 0)
    )

    # --- 3. Deduplicate on order_item_id (keep latest by order_id) ---
    window = Window.partitionBy("order_item_id").orderBy(F.col("order_id").desc())
    clean = (
        clean
        .withColumn("_row_num", F.row_number().over(window))
        .filter(F.col("_row_num") == 1)
        .drop("_row_num")
    )

    # --- 4. Joins + computed columns ---
    fact = (
        clean
        .join(F.broadcast(customers), on="customer_id", how="left")
        .join(F.broadcast(products),  on="product_id",  how="left")
        .withColumnRenamed("country",  "customer_country")
        .withColumnRenamed("category", "product_category")
        .withColumn(
            "gross_revenue",
            F.round(F.col("quantity") * F.col("unit_price"), 2)
        )
        .withColumn(
            "gross_margin",
            F.round(F.col("quantity") * (F.col("unit_price") - F.col("unit_cost")), 2)
        )
        .withColumn(
            "margin_pct",
            F.when(
                F.col("gross_revenue") == 0,
                F.lit(None).cast("double")
            ).otherwise(
                F.round((F.col("gross_margin") / F.col("gross_revenue")) * 100, 2)
            )
        )
        .withColumn("etl_run_id", F.lit(etl_run_id))
        .select(
            "order_item_id",
            "order_id",
            "order_date",
            "customer_id",
            "customer_tier",
            "customer_country",
            "product_id",
            "product_category",
            "quantity",
            "unit_price",
            "unit_cost",
            "gross_revenue",
            "gross_margin",
            "margin_pct",
            "channel",
            "etl_run_id",
        )
    )

    return fact

