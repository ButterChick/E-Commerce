def run_pipeline(
    orders_filepath: str,
    oltp_host: str = "localhost",
    oltp_db: str = "ecommerce_oltp",
    oltp_user: str = "postgres",
    oltp_password: str = "admin",
    oltp_port: str = "5432",
    dw_host: str = "localhost",
    dw_db: str = "ecommerce_dw",
    dw_user: str = "postgres",
    dw_password: str = "admin",
    dw_port: str = "5432",
    dw_table: str = "fact_order_items",
    dag_id: str = "manual",
    processed_base: str = "data/processed",
) -> DataFrame:
    """
    Full ETL run: extract → transform → write Parquet → load → validate.

    The run_id is generated here and flows through transform(), write_parquet(),
    and load.run_all_loads() so every fact row, summary row, and audit log
    entry share the same identifier.

    The partition date is parsed from the filepath (expects dt=YYYY-MM-DD in
    the directory path, e.g. data/raw/dt=2026-06-01/orders.csv).

    Args:
        orders_filepath: Path to the orders CSV.
        oltp_*:          Connection parameters for the OLTP Postgres database.
        dw_*:            Connection parameters for the warehouse Postgres database.
        dag_id:          Airflow DAG ID or 'manual' for local runs.
        processed_base:  Root path for Parquet output (default: data/processed).

    Returns:
        Transformed Spark DataFrame (also persisted to Parquet and warehouse).
    """
    import re
    from load import run_all_loads

    spark = get_spark()

    # --- Partition date ---
    match = re.search(r"dt=(\d{4}-\d{2}-\d{2})", orders_filepath)
    partition_date = match.group(1) if match else None
    if not partition_date:
        raise ValueError(
            f"Cannot parse partition date from filepath: {orders_filepath}. "
            "Expected a dt=YYYY-MM-DD directory component."
        )
    print(f"\nPartition date: {partition_date}")

    # --- Single run_id for the entire pipeline run ---
    run_id = str(uuid.uuid4())
    print(f"ETL run ID: {run_id}")

    # --- Connection params ---
    oltp_jdbc_url = f"jdbc:postgresql://{oltp_host}:{oltp_port}/{oltp_db}"
    oltp_jdbc_props = {
        "user": oltp_user,
        "password": oltp_password,
        "driver": "org.postgresql.Driver",
    }

    dw_jdbc_url = f"jdbc:postgresql://{dw_host}:{dw_port}/{dw_db}"
    dw_jdbc_props = {
        "user": dw_user,
        "password": dw_password,
        "driver": "org.postgresql.Driver",
    }
    dw = {
        "host": dw_host,
        "port": dw_port,
        "db": dw_db,
        "user": dw_user,
        "password": dw_password,
    }

    # --- Extract ---
    orders    = extract_orders(spark, orders_filepath)
    customers = extract_customers(spark, oltp_jdbc_url, oltp_jdbc_props)
    products  = extract_products(spark, oltp_jdbc_url, oltp_jdbc_props)

    # --- Transform ---
    fact = transform(orders, customers, products, etl_run_id=run_id)
    log_quality(fact)

    # --- Write Parquet (decouple transform from load) ---
    parquet_paths = write_parquet(fact, partition_date, base_path=processed_base)

    # --- Load + Validate (reads from Parquet, not in-memory DataFrame) ---
    run_all_loads(
        spark=spark,
        fact_path=parquet_paths["fact_path"],
        summary_path=parquet_paths["summary_path"],
        jdbc_url=dw_jdbc_url,
        jdbc_props=dw_jdbc_props,
        dw=dw,
        partition_date=partition_date,
        etl_run_id=run_id,
        dag_id=dag_id,
    )

    return fact

