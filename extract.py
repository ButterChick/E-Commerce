def write_parquet(fact: DataFrame, partition_date: str, base_path: str = "data/processed") -> dict:
    """
    Write the transformed fact DataFrame and its daily summary to Parquet.

    Outputs two directories under base_path/dt=YYYY-MM-DD/:
      - fact/       — one row per order line item
      - summary/    — daily_category_sales grain

    Partitioned files make each step independently re-runnable: the load
    step reads from Parquet rather than holding the DataFrame in memory.

    Args:
        fact:           Output of transform().
        partition_date: 'YYYY-MM-DD' string used as the directory name.
        base_path:      Root directory for processed output (default: data/processed).

    Returns:
        Dict with keys 'fact_path' and 'summary_path'.
    """
    from pyspark.sql import functions as F

    fact_path    = f"{base_path}/dt={partition_date}/fact"
    summary_path = f"{base_path}/dt={partition_date}/summary"

    # Fact table
    (
        fact.write
        .mode("overwrite")
        .parquet(fact_path)
    )
    print(f"[write_parquet] Fact written to {fact_path}")

    # Daily summary — reuse the same aggregation logic as load.py
    summary = (
        fact
        .groupBy("order_date", "product_category", "customer_country")
        .agg(
            F.countDistinct("order_id").alias("order_count"),
            F.sum("quantity").cast("integer").alias("units_sold"),
            F.round(F.sum("gross_revenue"), 2).alias("gross_revenue"),
            F.round(F.sum("gross_margin"), 2).alias("gross_margin"),
            F.round(F.avg("gross_revenue"), 2).alias("avg_order_value"),
        )
        .withColumnRenamed("order_date", "summary_date")
    )

    (
        summary.write
        .mode("overwrite")
        .parquet(summary_path)
    )
    print(f"[write_parquet] Summary written to {summary_path}")

    return {"fact_path": fact_path, "summary_path": summary_path}



